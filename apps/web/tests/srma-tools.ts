import assert from "node:assert/strict";
import { parseReferences, deduplicateReferences, referencesRis, screeningCsv, continuousEffect, changeSd } from "../src/lib/research-tools";
import { wordTemplate } from "../src/lib/word-template";
const ris = "TY  - JOUR\nTI  - Trial A\nAU  - Smith, J\nPY  - 2020\nDO  - https://doi.org/10.1000/A\nER  - \n";
const nbib = "PMID- 123\nTI  - Trial A\nAU  - Smith, J\nDP  - 2020 Jan\nLID - 10.1000/a [doi]\nAB  - Important abstract\n      continued.\n\nPMID- 124\nTI  - Trial B\nAU  - Jane, A\nDP  - 2021\n\n";
const refs = [...parseReferences(ris), ...parseReferences(nbib)];
assert.equal(refs.length, 3);
const dedup = deduplicateReferences(refs);
assert.equal(dedup.unique.length, 2); assert.equal(dedup.duplicates.length, 1);
assert.equal(dedup.unique[0].abstract, "Important abstract continued.");
assert.equal(parseReferences(referencesRis(dedup.unique)).length, 2);
assert.equal(deduplicateReferences([{ ...refs[0], doi: "10.1000/a" }, { ...refs[0], doi: "10.1000/b" }]).unique.length, 2, "Conflicting DOIs must not merge by title");
assert.equal(deduplicateReferences([{ ...refs[0], doi: "10.1000/a" }, { ...refs[0], doi: "10.1000/b" }, { ...refs[0], doi: "" }]).unique.length, 3, "Ambiguous title matches must remain separate");
assert.equal(deduplicateReferences([{ ...refs[0], doi: "", year: "", authors: [] }, { ...refs[0], doi: "", year: "", authors: [] }]).unique.length, 2);
assert.ok(screeningCsv([{ ...refs[0], title: '=HYPERLINK("x")', reason: 'Line "quoted"' }]).includes("'=HYPERLINK"));
const effect = continuousEffect(50, 10, 2, 50, 8, 2);
assert.equal(effect.md, 2); assert.equal(effect.cohenD, 1); assert.ok(Math.abs(effect.seMD - 0.4) < 1e-12);
assert.ok(effect.hedgesG < effect.cohenD);
assert.equal(changeSd(2, 2, 0.5), 2); assert.equal(changeSd(2, 2, 1), 0);
assert.throws(() => changeSd(2, 2, 1.1)); assert.throws(() => continuousEffect(1, 10, 2, 50, 8, 2));
const docx = wordTemplate("A & B", "<Sample>\nUnicode: penelitian");
assert.equal(new DataView(docx.buffer).getUint32(0, true), 0x04034b50);
const decoded = new TextDecoder().decode(docx);
assert.ok(decoded.includes("A &amp; B")); assert.ok(decoded.includes("&lt;Sample&gt;"));
assert.ok(decoded.includes("[Content_Types].xml")); assert.ok(decoded.includes("word/document.xml"));
console.log("SR-MA: parser RIS/NBIB, deduplikasi, ekspor, effect size, validasi, dan paket DOCX lulus.");
